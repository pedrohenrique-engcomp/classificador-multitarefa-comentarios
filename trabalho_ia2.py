# 2. Criar a Classe de Dataset (Versão Padrão)
class MultiTaskDataset(Dataset):

    # Removido 'augmenter' do init
    def __init__(self, dataframe, tokenizer, max_len, tasks):
        self.dataframe = dataframe
        self.tokenizer = tokenizer
        self.max_len = max_len
        self.tasks = tasks
        self.texts = self.dataframe["comment_text"].tolist()
        self.labels = self.dataframe[tasks].values
        # A linha 'self.augmenter' foi removida

    def __len__(self):
        return len(self.texts)

    def __getitem__(self, idx):
        text = self.texts[idx]
        labels = self.labels[idx]

        # O bloco 'if self.augmenter:' foi removido

        encoding = self.tokenizer.encode_plus(
            text,
            add_special_tokens=True,
            max_length=self.max_len,
            padding='max_length',
            truncation=True,
            return_token_type_ids=False,
            return_attention_mask=True,
            return_tensors='pt',
        )

        return {
            'input_ids': encoding['input_ids'].flatten(),
            'attention_mask': encoding['attention_mask'].flatten(),
            'labels': torch.tensor(labels, dtype=torch.long)
        }

# 3. Criar os DataLoaders (Versão Padrão)
def create_data_loader(df, tokenizer, max_len, batch_size, tasks):
    ds = MultiTaskDataset(
        dataframe=df,
        tokenizer=tokenizer,
        max_len=max_len,
        tasks=tasks
        # O parâmetro 'augmenter' foi removido
    )

    # Voltamos a usar 'num_workers=2' para um carregamento mais rápido,
    # já que não temos mais o 'nltk' para causar conflitos.
    return DataLoader(
        ds,
        batch_size=batch_size,
        num_workers=2
    )

