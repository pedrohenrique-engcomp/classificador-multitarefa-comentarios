# --- 3. Funções de Treino e Avaliação ---

def train_epoch(model, data_loader, optimizer, device, scheduler):
    model.train()
    total_loss = 0
    all_preds = {task: [] for task in SELECTED_CLASSES}
    all_labels = {task: [] for task in SELECTED_CLASSES}

    for batch in tqdm(data_loader, desc="Treinando", leave=False):
        input_ids = batch["input_ids"].to(device)
        attention_mask = batch["attention_mask"].to(device)
        labels = batch["labels"].to(device)

        optimizer.zero_grad()
        list_of_logits = model(input_ids, attention_mask)

        current_loss = 0
        for i, task_name in enumerate(SELECTED_CLASSES):
            logits_task = list_of_logits[i]
            labels_task = labels[:, i]

            # [MUDANÇA] Loss padrão para todas as tarefas
            task_loss = loss_function(logits_task, labels_task)
            current_loss += task_loss

            preds = torch.argmax(logits_task, dim=1)
            all_preds[task_name].extend(preds.cpu().numpy())
            all_labels[task_name].extend(labels_task.cpu().numpy())

        total_loss += current_loss.item()

        # [MUDANÇA] Otimização normal (sem acumulação)
        current_loss.backward()
        nn.utils.clip_grad_norm_(model.parameters(), max_norm=1.0)
        optimizer.step()
        scheduler.step()

    avg_loss = total_loss / len(data_loader)

    f1_scores = {}
    for task_name in SELECTED_CLASSES:
        if task_name in ['onca', 'noticia']:
            f1 = f1_score(all_labels[task_name], all_preds[task_name], average='macro', zero_division=0)
        else:
            f1 = f1_score(all_labels[task_name], all_preds[task_name], average='binary', pos_label=1, zero_division=0)
        f1_scores[task_name] = f1

    return avg_loss, f1_scores


def eval_epoch(model, data_loader, device):
    model.eval()
    total_loss = 0
    all_preds = {task: [] for task in SELECTED_CLASSES}
    all_labels = {task: [] for task in SELECTED_CLASSES}

    with torch.no_grad():
        for batch in tqdm(data_loader, desc="Validando", leave=False):
            input_ids = batch["input_ids"].to(device)
            attention_mask = batch["attention_mask"].to(device)
            labels = batch["labels"].to(device)
            list_of_logits = model(input_ids, attention_mask)

            current_loss = 0
            for i, task_name in enumerate(SELECTED_CLASSES):
                logits_task = list_of_logits[i]
                labels_task = labels[:, i]

                # [MUDANÇA] Loss padrão
                task_loss = loss_function(logits_task, labels_task)
                current_loss += task_loss

                preds = torch.argmax(logits_task, dim=1)
                all_preds[task_name].extend(preds.cpu().numpy())
                all_labels[task_name].extend(labels_task.cpu().numpy())

            total_loss += current_loss.item()

    avg_loss = total_loss / len(data_loader)

    f1_scores = {}
    for task_name in SELECTED_CLASSES:
        if task_name in ['onca', 'noticia']:
            f1 = f1_score(all_labels[task_name], all_preds[task_name], average='macro', zero_division=0)
        else:
            f1 = f1_score(all_labels[task_name], all_preds[task_name], average='binary', pos_label=1, zero_division=0)
        f1_scores[task_name] = f1

    return avg_loss, f1_scores


