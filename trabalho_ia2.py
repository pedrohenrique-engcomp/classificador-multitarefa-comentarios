# CÉLULA 6: MODELO DistilBERT PARA CLASSIFICAÇÃO (Multi-Tarefa)

import torch.nn as nn
# [MUDANÇA]
from transformers import DistilBertModel

NUM_LABELS_PER_TASK = [3, 2, 3]


class MultiTaskClassifier(nn.Module):

    def __init__(self, model_name, num_labels_per_task):
        super(MultiTaskClassifier, self).__init__()
        self.num_tasks = len(num_labels_per_task)

        # [MUDANÇA] Usamos o DistilBertModel como "corpo"
        self.bert = DistilBertModel.from_pretrained(model_name)

        # Usamos o Dropout padrão (0.1)
        self.dropout = nn.Dropout(p=0.1)

        self.classifier_heads = nn.ModuleList()
        for num_labels in num_labels_per_task:
            # [MUDANÇA] O hidden_size do DistilBERT é 768
            head = nn.Linear(self.bert.config.hidden_size, num_labels)
            self.classifier_heads.append(head)

    def forward(self, input_ids, attention_mask):
        # [MUDANÇA] O DistilBERT não tem 'pooler_output'
        outputs = self.bert(
            input_ids=input_ids,
            attention_mask=attention_mask
        )

        # Pegamos o 'last_hidden_state'
        last_hidden_state = outputs.last_hidden_state

        # Usamos a saída do token [CLS] (índice 0) como o "resumo"
        pooled_output = last_hidden_state[:, 0]

        pooled_output = self.dropout(pooled_output)

        all_logits = []
        for head in self.classifier_heads:
            logits_task = head(pooled_output)
            all_logits.append(logits_task)

        return all_logits

# Instanciar o modelo e enviar para a GPU
